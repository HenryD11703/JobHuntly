using JobHuntly.Domain.Entities;
using Microsoft.EntityFrameworkCore;

namespace JobHuntly.Infrastructure.Data;

public class AppDbContext(DbContextOptions<AppDbContext> options) : DbContext(options)
{
    public DbSet<User> Users { get; set; } = null!;
    public DbSet<JobApplication> JobApplications { get; set; } = null!;
    public DbSet<Interview> Interviews { get; set; } = null!;
    public DbSet<ApplicationEvent> ApplicationEvents { get; set; } = null!;
    public DbSet<Debrief> Debriefs { get; set; } = null!;
    public DbSet<Story> Stories { get; set; } = null!;
    public DbSet<Offer> Offers { get; set; } = null!;
    public DbSet<AiUsage> AiUsages { get; set; } = null!;

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        base.OnModelCreating(modelBuilder);

        // Ids are always generated by the application. Declaring that lets EF treat a new child that
        // is added to a tracked parent as Added (not Modified).
        modelBuilder.Entity<User>().Property(u => u.Id).ValueGeneratedNever();
        modelBuilder.Entity<JobApplication>().Property(j => j.Id).ValueGeneratedNever();
        modelBuilder.Entity<Interview>().Property(i => i.Id).ValueGeneratedNever();
        modelBuilder.Entity<ApplicationEvent>().Property(e => e.Id).ValueGeneratedNever();
        modelBuilder.Entity<Debrief>().Property(d => d.Id).ValueGeneratedNever();
        modelBuilder.Entity<Story>().Property(s => s.Id).ValueGeneratedNever();
        modelBuilder.Entity<Offer>().Property(o => o.Id).ValueGeneratedNever();

        modelBuilder.Entity<User>(b =>
        {
            b.HasIndex(u => u.Email).IsUnique();
            b.Property(u => u.Email).IsRequired().HasMaxLength(150);
            b.Property(u => u.UsdToGtq).HasPrecision(10, 4).HasDefaultValue(7.64m);
            b.Property(u => u.EurToGtq).HasPrecision(10, 4).HasDefaultValue(8.54m);
            b.Property(u => u.IsDemo).HasDefaultValue(false);
        });

        modelBuilder.Entity<JobApplication>(b =>
        {
            b.HasOne(j => j.User).WithMany(u => u.JobApplications).HasForeignKey(j => j.UserId).OnDelete(DeleteBehavior.Cascade);
            b.Property(j => j.Source).HasConversion<string>().HasMaxLength(30);
            b.Property(j => j.Location).HasMaxLength(150);
            b.HasIndex(j => j.UserId);
        });

        modelBuilder.Entity<Interview>(b =>
        {
            b.HasOne(i => i.JobApplication).WithMany(j => j.Interviews).HasForeignKey(i => i.JobApplicationId).OnDelete(DeleteBehavior.Cascade);
            b.Property(i => i.RoundType).HasConversion<string>().HasMaxLength(30);
            b.Property(i => i.Status).HasConversion<string>().HasMaxLength(30).HasDefaultValue(InterviewStatus.Scheduled);
        });

        modelBuilder.Entity<ApplicationEvent>(b =>
        {
            b.HasOne(e => e.JobApplication).WithMany(j => j.Events).HasForeignKey(e => e.JobApplicationId).OnDelete(DeleteBehavior.Cascade);
            b.Property(e => e.Type).HasConversion<string>().HasMaxLength(30);
            b.Property(e => e.Note).HasMaxLength(1000);
            b.HasIndex(e => new { e.JobApplicationId, e.OccurredAt });
        });

        modelBuilder.Entity<Debrief>(b =>
        {
            b.HasOne(d => d.Interview).WithOne(i => i.Debrief).HasForeignKey<Debrief>(d => d.InterviewId).OnDelete(DeleteBehavior.Cascade);
            b.HasIndex(d => d.InterviewId).IsUnique();
        });

        modelBuilder.Entity<Story>(b =>
        {
            b.HasOne(s => s.User).WithMany(u => u.Stories).HasForeignKey(s => s.UserId).OnDelete(DeleteBehavior.Cascade);
            b.Property(s => s.Title).HasMaxLength(150);
            b.HasIndex(s => s.UserId);
        });

        modelBuilder.Entity<Offer>(b =>
        {
            b.HasOne(o => o.JobApplication).WithMany(j => j.Offers).HasForeignKey(o => o.JobApplicationId).OnDelete(DeleteBehavior.Cascade);
            b.Property(o => o.Amount).HasPrecision(14, 2);
            b.Property(o => o.Currency).HasConversion<string>().HasMaxLength(3);
            b.Property(o => o.Period).HasConversion<string>().HasMaxLength(10);
            b.Property(o => o.Notes).HasMaxLength(2000);
        });
        modelBuilder.Entity<AiUsage>(b =>
        {
            b.ToTable("AiUsage");
            b.HasKey(a => new { a.UserId, a.Day });
            b.HasOne(a => a.User).WithMany().HasForeignKey(a => a.UserId).OnDelete(DeleteBehavior.Cascade);
        });
    }
}
